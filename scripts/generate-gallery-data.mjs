import { readdirSync, existsSync, readFileSync, writeFileSync } from "fs";
import { join, parse } from "path";
import { fileURLToPath } from "url";

const __dirname = join(fileURLToPath(import.meta.url), "..");
const ROOT = join(__dirname, "..");

const VIDEOS_DIR = join(ROOT, "public/videos/gallery");
const METADATA_PATH = join(VIDEOS_DIR, "metadata.json");

function loadMetadata() {
  if (!existsSync(METADATA_PATH)) return {};
  try {
    return JSON.parse(readFileSync(METADATA_PATH, "utf-8"));
  } catch {
    console.warn("⚠ metadata.json parse error — ignoring");
    return {};
  }
}

function altFor(filename, metadata) {
  const custom = metadata[filename] || metadata[filename.replace(/\.[^.]+$/, "")];
  if (custom) return custom;
  const name = parse(filename).name.replace(/^IMG_\d+/i, "").trim();
  if (!name) return `Video ${parse(filename).name}`;
  return name.replace(/[-_]/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}


const VIDEO_EXTS = new Set([".mp4", ".webm", ".mov", ".avi", ".mkv"]);

function scanVideos(metadata) {
  if (!existsSync(VIDEOS_DIR)) return [];
  const files = readdirSync(VIDEOS_DIR).filter((f) => f !== "metadata.json" && VIDEO_EXTS.has(parse(f).ext.toLowerCase()));
  files.sort();
  return files.map((file, i) => {
    const name = parse(file).name;
    const posterPath = `/images/gallery/${name}.jpg`;
    const posterExists = existsSync(join(ROOT, "public", posterPath));
    return {
      id: `vid-${i + 1}`,
      type: "video",
      src: `/videos/gallery/${file}`,
      ...(posterExists ? { poster: posterPath } : {}),
      alt: altFor(file, metadata),
    };
  });
}

function generate() {
  const metadata = loadMetadata();
  const videos = scanVideos(metadata);
  const items = [...IMAGES, ...videos];

  const code = `// Auto-generated by scripts/generate-gallery-data.mjs
// Do not edit manually. Add videos to public/videos/gallery/ and re-run build.

export interface GalleryItem {
  id: string;
  type: "image" | "video";
  src: string;
  poster?: string;
  alt: string;
}

export const galleryItems: GalleryItem[] = ${JSON.stringify(items, null, 2)};
`;

  writeFileSync(join(ROOT, "src/data/gallery.ts"), code, "utf-8");
  console.log(`✓ gallery data generated: ${IMAGES.length} images + ${videos.length} videos`);
}

generate();
